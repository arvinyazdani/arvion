"use strict";
const assert = require("node:assert/strict");
const { create } = require("./storefront-model.js");
const catalog = { products: [{ id: "vase", variants: [{ id: "sand", price: 100000, stock: 6 }, { id: "ink", price: 120000, stock: 0 }] }], shipping: [{ id: "pickup", fee: 0 }, { id: "delivery", fee: 90000 }] };
const basket = create(catalog);
assert.deepEqual(basket.totals("delivery"), { count: 0, subtotal: 0, shipping: 0, total: 0 });
assert.throws(() => basket.add("unknown", "sand", 1));
assert.throws(() => basket.add("vase", "ink", 1));
for (const value of [0, -1, 1.5, NaN, Infinity, "1", 7]) assert.throws(() => basket.add("vase", "sand", value));
assert.equal(basket.lines().length, 0);
basket.add("vase", "sand", 2); basket.add("vase", "sand", 1);
assert.equal(basket.lines().length, 1); assert.equal(basket.lines()[0].quantity, 3);
assert.deepEqual(basket.totals("delivery"), { count: 3, subtotal: 300000, shipping: 90000, total: 390000 });
assert.throws(() => basket.add("vase", "sand", 4));
assert.equal(basket.lines()[0].quantity, 3);
basket.setQuantity("vase:sand", 6); assert.equal(basket.totals("pickup").total, 600000);
assert.throws(() => basket.setQuantity("vase:sand", 0)); assert.throws(() => basket.setQuantity("vase:sand", 7));
const copy = basket.lines(); copy[0].quantity = 100; assert.equal(basket.lines()[0].quantity, 6);
assert.throws(() => basket.totals("unknown"));
basket.remove("vase:sand"); assert.equal(basket.totals("delivery").total, 0);
basket.add("vase", "sand", 1); basket.clear(); assert.equal(basket.lines().length, 0);
const another = create(catalog); another.add("vase", "sand", 1);
assert.equal(basket.lines().length, 0); assert.equal(another.lines().length, 1);
const multiple = create({products:[{id:"vase",variants:[{id:"sand",price:100000,stock:6},{id:"olive",price:110000,stock:6}]}],shipping:catalog.shipping});
multiple.add("vase", "sand", 1); multiple.add("vase", "olive", 2);
assert.equal(multiple.lines().length, 2); assert.equal(multiple.totals("delivery").total, 410000);
console.log("Storefront model: empty, variants, stock, quantity, merging, delivery, edits, isolation, remove and clear — passed");
