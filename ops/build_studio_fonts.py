"""Build-only: fonttools[woff]==4.60.1. Keep original fonts for other scripts.

This lossless glyph subset preserves shaping/layout features and outlines. It
does not change the font design, rasterise it or add a production dependency.
"""
import hashlib
import json
from pathlib import Path

from fontTools import subset
from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / 'core/static/core/fonts'
OUTPUT = FONTS / 'studio'
RANGES = ((0, 255), (0x600, 0x6ff), (0x2000, 0x206f), (0xfb50, 0xfeff))
CSS_RANGE = 'U+0000-00FF,U+0600-06FF,U+2000-206F,U+FB50-FEFF'


def build():
    OUTPUT.mkdir(exist_ok=True)
    manifest = {}
    rules = []
    for name, weight in (('Regular', '400'), ('Bold', '700 800'), ('Black', '900')):
        filename = f'Vazirmatn-{name}.woff2'
        source = FONTS / filename
        font = TTFont(source, recalcTimestamp=False)
        original = TTFont(source, recalcTimestamp=False)
        codepoints = [cp for cp in font.getBestCmap()
                      if any(start <= cp <= end for start, end in RANGES)]
        options = subset.Options()
        options.layout_features = ['*']
        options.name_IDs = ['*']
        options.name_legacy = True
        options.name_languages = ['*']
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=codepoints)
        sub.subset(font)
        expected_order = font.getGlyphOrder()
        font.flavor = 'woff2'
        target = OUTPUT / filename
        font.save(target)
        # Re-open the actual WOFF2, not the unencoded in-memory result. Verify
        # every retained glyph outline/advance, including Arabic shaping glyphs.
        encoded = TTFont(target)
        old_glyphs, new_glyphs = original.getGlyphSet(), encoded.getGlyphSet()
        names = dict(zip(encoded.getGlyphOrder(), expected_order))
        for glyph, old_name in names.items():
            before, after = RecordingPen(), RecordingPen()
            old_glyphs[old_name].draw(before)
            new_glyphs[glyph].draw(after)
            normalized = [(op, (names[args[0]], args[1]) if op == 'addComponent' else args)
                          for op, args in after.value]
            assert before.value == normalized, old_name
            assert original['hmtx'][old_name] == encoded['hmtx'][glyph], old_name
        assert all(names[encoded.getBestCmap()[cp]] == original.getBestCmap()[cp]
                   for cp in codepoints)
        manifest[filename] = { 'source': hashlib.sha256(source.read_bytes()).hexdigest(),
                              'subset': hashlib.sha256(target.read_bytes()).hexdigest(),
                              'builder': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                              'codepoints': len(codepoints)}
        # Declare exactly the other supported glyphs, not all Unicode. Otherwise
        # an arrow/emoji absent from Vazirmatn downloads the whole fallback font
        # merely to discover that its glyph is absent there too.
        remaining = sorted(set(original.getBestCmap()) - set(codepoints))
        fallback_range = ','.join(f'U+{cp:04X}' for cp in remaining)
        rules.append('@font-face{font-family:Vazirmatn;src:url("../fonts/' +
                     filename + '") format("woff2");font-weight:' + weight +
                     ';font-style:normal;font-display:swap;unicode-range:' + fallback_range + '}')
        rules.append('@font-face{font-family:Vazirmatn;src:url("../fonts/studio/' +
                     filename + '") format("woff2");font-weight:' + weight +
                     ';font-style:normal;font-display:swap;unicode-range:' + CSS_RANGE + '}')
    (OUTPUT / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    (ROOT / 'core/static/core/css/studio-fonts.generated.css').write_text(
        '/* Generated by ops/build_studio_fonts.py; full-font faces remain the fallback. */\n' +
        '\n'.join(rules) + '\n')
    print('Studio fonts:', sum((FONTS / name).stat().st_size for name in manifest),
          '→', sum((OUTPUT / name).stat().st_size for name in manifest), 'bytes')


if __name__ == '__main__':
    build()
