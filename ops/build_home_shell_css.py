"""Build the cinematic home adapter from canonical site.css, preserving cascade.

Build-only dependency: tinycss2==1.4.0 (not a production dependency).
Run in a tooling venv: python ops/build_home_shell_css.py [--check]
"""
import argparse
import hashlib
from pathlib import Path
import re

import tinycss2

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'core/static/core/css/site.css'
TARGET = ROOT / 'core/static/core/css/home-shell.generated.css'
# All public-shell states are retained, not merely selectors matching one screenshot.
PREFIXES = ('site-', 'nav-', 'menu-', 'brand-', 'mobile-', 'install-', 'welcome-',
            'message-', 'theme-', 'sound-', 'footer-', 'rvion-', 'ui-', 'is-')
EXACT = {'shell', 'brand', 'button', 'secondary', 'compact', 'skip-link', 'sr-only',
         'messages', 'message', 'menu-open', 'navigation-pending', 'eyebrow'}


def public_selector(tokens):
    text = tinycss2.serialize(tokens).strip()
    positive = re.sub(r':not\([^)]*\)', '', text)
    classes = re.findall(r'\.([a-zA-Z_][\w-]*)', positive)
    return text if all(name in EXACT or name.startswith(PREFIXES) for name in classes) else ''


def select_rules(rules):
    result = []
    for rule in rules:
        if rule.type == 'qualified-rule':
            parts, part = [], []
            for token in rule.prelude:
                if token.type == 'literal' and token.value == ',':
                    parts.append(part); part = []
                else:
                    part.append(token)
            parts.append(part)
            selectors = [s for s in map(public_selector, parts) if s]
            if selectors:
                result.append(','.join(selectors) + '{' + tinycss2.serialize(rule.content) + '}')
        elif rule.type == 'at-rule':
            if rule.lower_at_keyword in ('media', 'supports', 'layer') and rule.content:
                body = select_rules(tinycss2.parse_rule_list(rule.content, skip_whitespace=True, skip_comments=True))
                if body:
                    result.append('@' + rule.at_keyword + tinycss2.serialize(rule.prelude) + '{' + body + '}')
            else:
                result.append(tinycss2.serialize([rule]))
        elif rule.type == 'error':
            raise ValueError('Canonical CSS parse error: ' + rule.message)
    return '\n'.join(result)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    original = SOURCE.read_bytes()
    content = '/* Generated by ops/build_home_shell_css.py; do not hand-edit.\n Source SHA256: ' + hashlib.sha256(original).hexdigest()
    content += '\n Builder SHA256: ' + hashlib.sha256(Path(__file__).read_bytes()).hexdigest() + ' */\n'
    content += select_rules(tinycss2.parse_stylesheet(original.decode(), skip_whitespace=True, skip_comments=True)) + '\n'
    if args.check:
        if TARGET.read_text() != content:
            raise SystemExit('Home shell CSS is stale; regenerate the adapter.')
    else:
        TARGET.write_text(content)
    print('Home shell CSS:', len(original), '→', len(content.encode()), 'bytes; cascade/source retained.')


if __name__ == '__main__':
    main()
